export const heroes = [
  { id: 'rabbit', label: 'خرگوش برفی', icon: 'Rabbit' },
  { id: 'fish', label: 'ماهی قرمز', icon: 'Fish' },
  { id: 'bird', label: 'کبوتر ماه', icon: 'Bird' }
];

export const topics = [
  { id: 'kindness', label: 'مهربانی' },
  { id: 'friendship', label: 'دوستی' },
  { id: 'courage', label: 'شجاعت' },
  { id: 'sleep', label: 'خواب آرام' },
  { id: 'teeth', label: 'مسواک زدن' }
];

const END = 'قصهٔ ما به سر رسید، کلاغه به خونه‌اش نرسید.';

/* شروع و پایان هر قهرمان؛ وسط قصه از موضوع می‌آید */
const heroParts = {
  rabbit: {
    noun: 'خرگوش',
    open: (n) => [
      `یکی بود، یکی نبود. شبی که ماه گرد و روشن بالای پشت‌بام‌ها ایستاده بود، ${n} توی رختخواب گرمش دراز کشیده بود و از پنجره ستاره‌ها را می‌شمرد.`,
      'تق، تق، تق! پشت پنجره خرگوش سفیدی ایستاده بود که گوش‌هایش زیر نور ماه نقره‌ای شده بود. گفت: «سلام! امشب آمده‌ام تا با هم یک ماجرا داشته باشیم.»'
    ],
    close: (n) => `خرگوش گوش‌هایش را آرام تکان داد و گفت: «شب بخیر، ${n}.» و میان نور نقره‌ای ماه ناپدید شد. ${END}`
  },
  fish: {
    noun: 'ماهی قرمز',
    open: (n) => [
      `یکی بود، یکی نبود. کنار پنجرهٔ اتاق ${n}، توی تنگ بلور، ماهی قرمز کوچکی بود که هر شب زیر نور ماه حباب می‌ساخت.`,
      'آن شب ماهی قرمز دمش را تکان داد و آهسته گفت: «امشب ماه توی آب من افتاده؛ بیا با هم یک ماجرا داشته باشیم.»'
    ],
    close: (n) => `ماهی قرمز یک حباب گرد ساخت که ماه تویش برق می‌زد و گفت: «شب بخیر، ${n}.» ${END}`
  },
  bird: {
    noun: 'کبوتر',
    open: (n) => [
      `یکی بود، یکی نبود. شب آرامی بود و ${n} داشت ستاره‌ها را از پشت پنجره تماشا می‌کرد که کبوتر سفیدی روی لب پنجره نشست.`,
      'کبوتر گفت: «من نامه‌رسان ماهم. ماه گفته امشب پیش تو بیایم تا با هم یک ماجرا داشته باشیم.»'
    ],
    close: (n) => `کبوتر بال‌هایش را باز کرد و گفت: «شب بخیر، ${n}. ماه سلام رساند.» و به آسمان پر کشید. ${END}`
  }
};

const topicParts = {
  kindness: (n, h) => [
    `${h} گفت: «امشب ستاره‌ها کم‌اند. می‌گویند هر کس امروز یک کار مهربانانه کرده باشد، یک ستاره روشن می‌کند.»`,
    `${n} یادش آمد که امروز اسباب‌بازی‌اش را با دوستش قسمت کرده. همان لحظه بالای گنبد، ستارهٔ تازه‌ای روشن شد و ${h} از خوشحالی دور خودش چرخید.`
  ],
  friendship: (n, h) => [
    `${h} گفت: «آن طرف باغ، جوجه‌تیغی کوچکی هست که هیچ دوستی ندارد، چون همه از تیغ‌هایش می‌ترسند.» ${n} فکری کرد و گفت: «شاید فقط منتظر کسی است که اول سلام کند.»`,
    `${n} و ${h} زیر نور ماه پیش جوجه‌تیغی رفتند و سلام کردند. جوجه‌تیغی آن‌قدر خوشحال شد که تیغ‌هایش نرم شد، و از آن شب سه دوست شدند.`
  ],
  courage: (n, h) => [
    `${h} گفت: «گوشهٔ اتاق سایهٔ بزرگی هست که خیلی‌ها از آن می‌ترسند.» ${n} اول کمی ترسید، ولی کنار ${h} ماند و چراغ‌قوه را روشن کرد.`,
    `سایه چیزی نبود جز یک جوراب تنها که دنبال جفتش می‌گشت! ${n} خندید و جوراب را به جفتش رساند. ${h} گفت: «دیدی؟ شجاعت یعنی با وجود ترس، یک قدم جلو برویم.»`
  ],
  sleep: (n, h) => [
    `${h} گفت: «می‌دانی ستاره‌ها چطور می‌خوابند؟ آرام نفس می‌کشند؛ یک نفس از بینی، و یک نفس آهسته بیرون.» ${n} هم همراه ${h} نفس کشید: یک، دو، سه.`,
    'با هر نفس دست‌ها سنگین‌تر و پلک‌ها گرم‌تر شد. ماه پتوی نقره‌ای‌اش را روی شهر کشید و همه‌جا آرام شد.'
  ],
  teeth: (n, h) => [
    `${h} گفت: «امشب دندان‌هایم خبر بدی دادند؛ می‌گویند میکروب‌های شیرینی‌خوار مهمانی گرفته‌اند!» ${n} خندید و مسواکش را آورد.`,
    `${n} و ${h} با هم دو دقیقه مسواک زدند: بالا و پایین، دندان‌های جلو و عقب. میکروب‌ها روی کف سفید سُر خوردند و رفتند، و دندان‌ها مثل ستاره برق زدند.`
  ]
};

export function makeStory(name, heroId, topicId) {
  const n = name.trim();
  const hero = heroParts[heroId] || heroParts.rabbit;
  const heroLabel = (heroes.find((h) => h.id === heroId) || heroes[0]).label;
  const middle = (topicParts[topicId] || topicParts.kindness)(n, hero.noun);
  return {
    title: `${n} و ${heroLabel}`,
    parts: [...hero.open(n), ...middle, hero.close(n)]
  };
}
